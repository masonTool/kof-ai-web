/**
 * 构图与画法约束同样锁死。
 *
 * `height` 是"人物占画面高度的百分比"：AI 默认一律画满 85%，
 * 于是蹲姿会被它画得和站姿一样高——**整个人大一圈**。蹲姿必须自己降下来。
 */
function frame(height = 85) {
  return [
    `严格侧身朝右，全身像，脚踩在画面底边，人物占画面高度 ${height}%，水平居中。`,
    '纯洋红色背景（#FF00FF）平涂，无地面、无阴影、无文字、无水印、无边框。',
  ].join('');
}

